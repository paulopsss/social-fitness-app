-- =====================================================================
-- Fitly database schema, version 1
-- Creates every table in third normal form (3NF), with primary keys,
-- foreign keys, CHECK constraints and indexes.
-- Run automatically by Flyway when the app starts.
-- Written in standard SQL that runs on H2 (our database, ADR 5) and PostgreSQL.
-- =====================================================================

-- ---------------------------------------------------------------------
-- users: one row per account. Email is the login name, so it is unique.
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(254) NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    display_name   VARCHAR(50),
    bio            VARCHAR(500),
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email UNIQUE (email)
);

-- ---------------------------------------------------------------------
-- workout_types: lookup table ("Running", "Yoga", ...).
-- Pulled out of workouts so a type's category is stored once (3NF).
-- ---------------------------------------------------------------------
CREATE TABLE workout_types (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(50) NOT NULL,
    category  VARCHAR(20) NOT NULL,
    CONSTRAINT uq_workout_types_name UNIQUE (name),
    CONSTRAINT ck_workout_types_category
        CHECK (category IN ('CARDIO', 'STRENGTH', 'FLEXIBILITY', 'SPORT', 'MIND_BODY'))
);

-- ---------------------------------------------------------------------
-- workouts: one logged session (Use Case 2: Log Workout).
-- ---------------------------------------------------------------------
CREATE TABLE workouts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL,
    workout_type_id   BIGINT       NOT NULL,
    workout_date      DATE         NOT NULL,
    duration_minutes  INT          NOT NULL,
    calories          INT          NOT NULL DEFAULT 0,
    notes             VARCHAR(500),
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_workouts_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_workouts_type FOREIGN KEY (workout_type_id)
        REFERENCES workout_types (id) ON DELETE RESTRICT,
    CONSTRAINT ck_workouts_duration CHECK (duration_minutes > 0),
    CONSTRAINT ck_workouts_calories CHECK (calories >= 0)
);
-- The feed and weekly goal progress both ask "this user's workouts by date".
CREATE INDEX ix_workouts_user_date ON workouts (user_id, workout_date);
CREATE INDEX ix_workouts_type ON workouts (workout_type_id);

-- ---------------------------------------------------------------------
-- exercises: catalog of movements ("Squat", "Bench Press", ...).
-- ---------------------------------------------------------------------
CREATE TABLE exercises (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(80) NOT NULL,
    muscle_group  VARCHAR(30) NOT NULL,
    CONSTRAINT uq_exercises_name UNIQUE (name)
);

-- ---------------------------------------------------------------------
-- workout_exercises: associative table for the many-to-many between
-- workouts and exercises, holding the sets, reps and weight for each pair.
-- ---------------------------------------------------------------------
CREATE TABLE workout_exercises (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_id   BIGINT       NOT NULL,
    exercise_id  BIGINT       NOT NULL,
    sets         INT          NOT NULL,
    reps         INT          NOT NULL,
    weight_kg    DECIMAL(6, 2),
    CONSTRAINT fk_workout_exercises_workout FOREIGN KEY (workout_id)
        REFERENCES workouts (id) ON DELETE CASCADE,
    CONSTRAINT fk_workout_exercises_exercise FOREIGN KEY (exercise_id)
        REFERENCES exercises (id) ON DELETE RESTRICT,
    CONSTRAINT uq_workout_exercises_pair UNIQUE (workout_id, exercise_id),
    CONSTRAINT ck_workout_exercises_sets CHECK (sets > 0),
    CONSTRAINT ck_workout_exercises_reps CHECK (reps > 0),
    CONSTRAINT ck_workout_exercises_weight CHECK (weight_kg IS NULL OR weight_kg >= 0)
);
CREATE INDEX ix_workout_exercises_exercise ON workout_exercises (exercise_id);

-- ---------------------------------------------------------------------
-- goals: a user's weekly target (minutes, workouts, or calories).
-- ---------------------------------------------------------------------
CREATE TABLE goals (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL,
    goal_type     VARCHAR(30) NOT NULL,
    target_value  INT         NOT NULL,
    start_date    DATE        NOT NULL,
    end_date      DATE,
    status        VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_goals_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_goals_type
        CHECK (goal_type IN ('WEEKLY_MINUTES', 'WEEKLY_WORKOUTS', 'WEEKLY_CALORIES')),
    CONSTRAINT ck_goals_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'ABANDONED')),
    CONSTRAINT ck_goals_target CHECK (target_value > 0),
    CONSTRAINT ck_goals_dates CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX ix_goals_user_status ON goals (user_id, status);

-- ---------------------------------------------------------------------
-- friendships: a friend request from one user to another.
-- users -> users is many-to-many, so it needs its own table.
-- ---------------------------------------------------------------------
CREATE TABLE friendships (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id  BIGINT      NOT NULL,
    addressee_id  BIGINT      NOT NULL,
    status        VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at  TIMESTAMP,
    CONSTRAINT fk_friendships_requester FOREIGN KEY (requester_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_friendships_addressee FOREIGN KEY (addressee_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_friendships_pair UNIQUE (requester_id, addressee_id),
    CONSTRAINT ck_friendships_not_self CHECK (requester_id <> addressee_id),
    CONSTRAINT ck_friendships_status CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED'))
);
CREATE INDEX ix_friendships_addressee ON friendships (addressee_id, status);

-- ---------------------------------------------------------------------
-- posts: something a user shares in the feed, optionally about a workout.
-- If the workout is deleted the post stays, it just loses the link.
-- ---------------------------------------------------------------------
CREATE TABLE posts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL,
    workout_id  BIGINT,
    content     VARCHAR(1000) NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_posts_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_posts_workout FOREIGN KEY (workout_id)
        REFERENCES workouts (id) ON DELETE SET NULL
);
CREATE INDEX ix_posts_user_created ON posts (user_id, created_at);
CREATE INDEX ix_posts_workout ON posts (workout_id);

-- ---------------------------------------------------------------------
-- comments: replies under a post.
-- ---------------------------------------------------------------------
CREATE TABLE comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     BIGINT       NOT NULL,
    user_id     BIGINT       NOT NULL,
    content     VARCHAR(500) NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comments_post FOREIGN KEY (post_id)
        REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_comments_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX ix_comments_post_created ON comments (post_id, created_at);
CREATE INDEX ix_comments_user ON comments (user_id);

-- ---------------------------------------------------------------------
-- post_likes: who liked which post. The composite primary key means a
-- user can like a given post only once.
-- ---------------------------------------------------------------------
CREATE TABLE post_likes (
    post_id     BIGINT    NOT NULL,
    user_id     BIGINT    NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_post_likes PRIMARY KEY (post_id, user_id),
    CONSTRAINT fk_post_likes_post FOREIGN KEY (post_id)
        REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_post_likes_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX ix_post_likes_user ON post_likes (user_id);
